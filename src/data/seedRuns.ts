import type { AgentRun, TraceStep, RunStatus, BenchmarkCategory } from '@/types';

let stepCounter = 0;
function sid(): string {
  stepCounter += 1;
  return `step-${stepCounter}`;
}

function makeStep(partial: Partial<TraceStep> & {
  stepType: TraceStep['stepType'];
  agentBelief: string;
  policyDecision: TraceStep['policyDecision'];
  policyReason: string;
}): TraceStep {
  const cost = partial.estimatedCost ?? 0;
  const tokens = partial.tokenUsage ?? 0;
  const cumCost = partial.cumulativeCost ?? cost;
  const cumTokens = partial.cumulativeTokens ?? tokens;
  return {
    id: sid(),
    stepNumber: partial.stepNumber ?? 0,
    timestamp: partial.timestamp ?? new Date().toISOString(),
    agentBelief: partial.agentBelief,
    stepType: partial.stepType,
    toolName: partial.toolName,
    toolDisplayName: partial.toolDisplayName,
    toolInputArgs: partial.toolInputArgs,
    toolOutputSummary: partial.toolOutputSummary,
    retryCount: partial.retryCount ?? 0,
    latencyMs: partial.latencyMs ?? 0,
    tokenUsage: tokens,
    estimatedCost: cost,
    cumulativeCost: cumCost,
    cumulativeTokens: cumTokens,
    policyDecision: partial.policyDecision,
    policyReason: partial.policyReason,
    recoveryStrategy: partial.recoveryStrategy ?? 'none',
    recoveryExplanation: partial.recoveryExplanation,
    betterRecoveryStrategy: partial.betterRecoveryStrategy,
    isFailurePoint: partial.isFailurePoint ?? false,
  };
}

interface RunTemplate {
  id: string;
  userRequest: string;
  agentVersion: string;
  modelConfig: string;
  policyProfileId: string;
  status: RunStatus;
  statusReason: string;
  benchmarkTaskId?: string;
  benchmarkCategory?: BenchmarkCategory;
  promptStrategy: string;
  daysAgo: number;
  steps: Array<Partial<TraceStep> & {
    stepType: TraceStep['stepType'];
    agentBelief: string;
    policyDecision: TraceStep['policyDecision'];
    policyReason: string;
  }>;
}

function buildRun(t: RunTemplate): AgentRun {
  stepCounter = 0;
  let cumCost = 0;
  let cumTokens = 0;
  const steps: TraceStep[] = [];
  let stepNum = 0;
  const baseDate = new Date(Date.now() - t.daysAgo * 86400000);

  for (const s of t.steps) {
    stepNum += 1;
    const cost = s.estimatedCost ?? 0;
    const tokens = s.tokenUsage ?? 0;
    cumCost += cost;
    cumTokens += tokens;
    const stepTime = new Date(baseDate.getTime() + stepNum * 5000).toISOString();
    steps.push(
      makeStep({
        ...s,
        stepNumber: stepNum,
        timestamp: stepTime,
        cumulativeCost: cumCost,
        cumulativeTokens: cumTokens,
      })
    );
  }

  const totalDuration = steps.reduce((a, s) => a + s.latencyMs, 0);
  const startTime = baseDate.toISOString();
  const endTime = new Date(baseDate.getTime() + totalDuration).toISOString();

  return {
    id: t.id,
    userRequest: t.userRequest,
    agentVersion: t.agentVersion,
    modelConfig: t.modelConfig,
    policyProfileId: t.policyProfileId,
    startTime,
    endTime,
    totalDurationMs: totalDuration,
    totalTokens: cumTokens,
    totalCost: Math.round(cumCost * 10000) / 10000,
    status: t.status,
    statusReason: t.statusReason,
    steps,
    benchmarkTaskId: t.benchmarkTaskId,
    benchmarkCategory: t.benchmarkCategory,
    promptStrategy: t.promptStrategy,
  };
}

